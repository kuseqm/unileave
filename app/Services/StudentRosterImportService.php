namespace App\Services;

use App\Models\Campus;
use App\Models\GraduationCeremony;
use App\Models\Program;
use App\Models\Student;
use App\Models\StudentGraduation;
use App\Models\StudentRosterImport;
use App\Models\University;
use App\Models\User;
use Carbon\Carbon;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Maatwebsite\Excel\Facades\Excel;

/**
 * Imports the "Graduation Roster" template - the minimum facts the
 * registry is actually certain of from the physical graduation books
 * (registration number, name, sex, graduation year), not a full academic
 * record. GPA, classification and exact degree wording are deliberately
 * left for later, filled in only when an actual verification request needs
 * them - see [[project_gmsa_graduation_verification_slice]].
 *
 * Campus, Programme and Graduation Year are chosen once on the import page
 * (a graduation book is naturally one campus, one programme and one
 * graduation year) rather than repeated on every row - matching how the
 * registry's own physical books are organised, and removing any need to
 * resolve an ambiguous Programme name per row. Campus is independent of
 * Programme - the same Programme is offered across every campus, so it
 * cannot be derived from Programme -> School.
 *
 * Column order matches exactly what downloadTemplate() writes - this
 * reads by fixed position rather than a heading-name lookup, since the
 * template is generated by this same feature and the layout is guaranteed.
 */
class StudentRosterImportService
{
    private const COL_REGISTRATION_NUMBER = 0;

    private const COL_SURNAME = 1;

    private const COL_FIRST_NAME = 2;

    private const COL_OTHER_NAMES = 3;

    private const COL_SEX = 4;

    private const COL_CERTIFICATE_NUMBER = 5;

    /**
     * The exact header row downloadTemplate() writes - the only thing
     * standing between this importer and reading a completely unrelated
     * spreadsheet as if it were a roster (mimes:xlsx,csv alone accepts any
     * spreadsheet of the right file type, not the right shape). A
     * mismatch here rejects the whole file up front instead of silently
     * misreading columns row by row.
     */
    private const EXPECTED_HEADERS = [
        'registration number', 'surname', 'first name', 'other names', 'sex (m/f)', 'certificate number (optional)',
    ];

    /**
     * Registration numbers before this graduation year used the same value
     * as the certificate number - confirmed by the registry.
     */
    private const LEGACY_CERTIFICATE_CUTOFF_YEAR = 2018;

    /**
     * How many rows one staged-import request processes. Small on purpose so
     * the progress bar advances visibly (and a request never runs long).
     */
    public const CHUNK_SIZE = 10;

    /**
     * One-shot import of a whole file (non-JS fallback and tests). The
     * browser flow uses stageRoster() + processStagedChunk() instead so it
     * can show real per-row progress.
     *
     * @return array{created: int, updated: int, flagged: array<int, array{row: int, registration_number: string, reason: string}>, error?: string}
     */
    public function import(UploadedFile $file, Campus $campus, Program $program, int $graduationYear, University $university, User $importer, ?int $rosterImportId = null): array
    {
        $report = ['created' => 0, 'updated' => 0, 'created_reg_numbers' => [], 'updated_reg_numbers' => [], 'flagged' => []];

        $read = $this->readDataRows($file);

        if (isset($read['error'])) {
            $report['error'] = $read['error'];

            return $report;
        }

        $ceremony = GraduationCeremony::where('year', $graduationYear)->first();

        foreach ($read['rows'] as $entry) {
            $this->importRow($entry['cells'], $entry['row'], $campus, $program, $graduationYear, $university, $importer, $rosterImportId, $ceremony, $report);
        }

        $this->flagMissingCeremony($ceremony, $graduationYear, $report);

        return $report;
    }

    /**
     * Reads and validates the file, then parks its data rows on disk so they
     * can be imported in small chunks by processStagedChunk().
     *
     * @return array{total: int}|array{error: string}
     */
    public function stageRoster(UploadedFile $file, StudentRosterImport $batch): array
    {
        $read = $this->readDataRows($file);

        if (isset($read['error'])) {
            return ['error' => $read['error']];
        }

        Storage::disk('local')->put($this->stagedPath($batch), json_encode($read['rows']));

        $batch->update(['total_rows' => count($read['rows']), 'processed_rows' => 0]);

        return ['total' => count($read['rows'])];
    }

    /**
     * Imports the next CHUNK_SIZE staged rows for this batch. Safe to call
     * again after an interruption - it resumes from `processed_rows`, and a
     * repeated row is only an update (rows match on registration number).
     *
     * @return array{processed: int, total: int, done: bool, report: array{created: int, updated: int, flagged: array<int, array{row: int, registration_number: string, reason: string}>}}
     */
    public function processStagedChunk(StudentRosterImport $batch, User $importer): array
    {
        $path = $this->stagedPath($batch);
        $rows = Storage::disk('local')->exists($path) ? json_decode(Storage::disk('local')->get($path), true) : [];

        $report = [
            'created' => (int) $batch->created_count,
            'updated' => (int) $batch->updated_count,
            'created_reg_numbers' => $batch->created_reg_numbers ?? [],
            'updated_reg_numbers' => $batch->updated_reg_numbers ?? [],
            'flagged' => $batch->flagged ?? [],
        ];

        $total = count($rows);
        $offset = (int) $batch->processed_rows;
        $ceremony = GraduationCeremony::where('year', $batch->graduation_year)->first();

        foreach (array_slice($rows, $offset, self::CHUNK_SIZE) as $entry) {
            $this->importRow($entry['cells'], $entry['row'], $batch->campus, $batch->program, (int) $batch->graduation_year, $batch->university, $importer, $batch->id, $ceremony, $report);
            $offset++;
        }

        $done = $offset >= $total;

        if ($done) {
            $this->flagMissingCeremony($ceremony, (int) $batch->graduation_year, $report);
            Storage::disk('local')->delete($path);
        }

        $batch->update([
            'processed_rows' => $offset,
            'created_count' => $report['created'],
            'updated_count' => $report['updated'],
            'created_reg_numbers' => $report['created_reg_numbers'],
            'updated_reg_numbers' => $report['updated_reg_numbers'],
            'flagged' => $report['flagged'],
        ]);

        return ['processed' => $offset, 'total' => $total, 'done' => $done, 'report' => $report];
    }

    /**
     * @return array{rows: array<int, array{row: int, cells: array<int, mixed>}>}|array{error: string}
     */
    private function readDataRows(UploadedFile $file): array
    {
        $rows = Excel::toCollection(null, $file)->first();

        if (! $rows) {
            return ['rows' => []];
        }

        if (! $this->hasExpectedHeaders($rows->first())) {
            return ['error' => 'This file does not match the Graduation Roster template - re-download the template from this page and fill it in without changing, reordering or renaming the column headers.'];
        }

        $dataRows = [];

        foreach ($rows->skip(1) as $index => $row) {
            $cells = $row instanceof Collection ? $row->all() : (array) $row;

            if (trim((string) ($cells[self::COL_REGISTRATION_NUMBER] ?? '')) === '') {
                continue;
            }

            $dataRows[] = ['row' => $index + 1, 'cells' => array_values($cells)];
        }

        return ['rows' => $dataRows];
    }

    private function stagedPath(StudentRosterImport $batch): string
    {
        return "roster-imports/{$batch->id}.json";
    }

    private function flagMissingCeremony(?GraduationCeremony $ceremony, int $graduationYear, array &$report): void
    {
        if (! $ceremony) {
            $report['flagged'][] = [
                'row' => 0,
                'registration_number' => '',
                'reason' => "No Graduation Ceremony is on file for {$graduationYear} - the exact ceremony date will be missing from letters until one is added.",
            ];
        }
    }

    /**
     * @param  array<int, mixed>  $row
     * @param  array{created: int, updated: int, flagged: array<int, array{row: int, registration_number: string, reason: string}>}  $report
     */
    private function importRow(array $row, int $rowNumber, Campus $campus, Program $program, int $graduationYear, University $university, User $importer, ?int $rosterImportId, ?GraduationCeremony $ceremony, array &$report): void
    {
        $registrationNumber = trim((string) ($row[self::COL_REGISTRATION_NUMBER] ?? ''));
        if ($registrationNumber === '') {
            return;
        }

        $surname = mb_strtoupper(trim((string) ($row[self::COL_SURNAME] ?? '')));
        $firstName = $this->titleCaseName(trim((string) ($row[self::COL_FIRST_NAME] ?? '')));
        $otherNames = $this->titleCaseName(trim((string) ($row[self::COL_OTHER_NAMES] ?? '')));
        $sexRaw = trim((string) ($row[self::COL_SEX] ?? ''));
        $certificateNumber = trim((string) ($row[self::COL_CERTIFICATE_NUMBER] ?? ''));

        if ($surname === '' || $firstName === '') {
            $report['flagged'][] = [
                'row' => $rowNumber,
                'registration_number' => $registrationNumber,
                'reason' => 'Required fields are missing (Surname / First Name).',
            ];

            return;
        }

        $gender = $this->normalizeSex($sexRaw);

        $durationYears = $program->duration_years ? (int) $program->duration_years : null;
        $startAcademicYear = $this->deriveStartAcademicYear($registrationNumber, $graduationYear, $durationYears);

        $student = Student::firstOrNew([
            'university_id' => $university->id,
            'registration_number' => $registrationNumber,
        ]);

        $fullName = trim("{$surname} {$firstName} {$otherNames}");

        $student->fill([
            'university_id' => $university->id,
            'registration_number' => $registrationNumber,
            'full_name' => $fullName,
            'last_name' => $surname,
            'first_name' => $firstName,
            'middle_name' => $otherNames ?: null,
            'gender' => $gender ?? $student->gender,
            'is_graduated' => true,
        ]);
        $student->save();

        $graduation = StudentGraduation::where('student_id', $student->id)
            ->where('graduation_year', $graduationYear)
            ->where('program_id', $program->id)
            ->where('campus_id', $campus->id)
            ->first();

        // Never overwrite a certificate barcode a graduation already has
        // (e.g. matched earlier via a real verification request) with
        // a blank re-import - only fill it in when it's still missing.
        $certificateBarcode = $graduation?->certificate_barcode
            ?: ($certificateNumber ?: ($graduationYear < self::LEGACY_CERTIFICATE_CUTOFF_YEAR ? $registrationNumber : null));

        $graduationData = [
            'university_id' => $university->id,
            'campus_id' => $campus->id,
            'program_id' => $program->id,
            'last_name' => $surname,
            'first_name' => $firstName,
            'middle_name' => $otherNames ?: null,
            'gender' => $gender ?? $student->gender,
            'graduation_year' => $graduationYear,
            'graduation_date' => $ceremony?->ceremony_date,
            'graduation_ceremony_number' => $ceremony?->sequence_number,
            'programme_start_academic_year' => $startAcademicYear,
            'programme_end_academic_year' => ($graduationYear - 1).'/'.$graduationYear,
            'programme_duration_years' => $durationYears ?? $student->programme_duration_years,
            'certificate_barcode' => $certificateBarcode,
            'imported_by' => $importer->id,
            'roster_import_id' => $rosterImportId,
        ];

        if ($graduation) {
            $oldAttributes = $graduation->attributesToArray();
            $rawDiff = [];

            foreach ($graduationData as $key => $value) {
                if (in_array($key, ['university_id', 'campus_id', 'imported_by', 'roster_import_id'], true)) {
                    continue;
                }

                $newValue = $value instanceof Carbon ? $value->toDateString() : $value;
                $oldValue = $oldAttributes[$key] ?? null;

                if ($oldValue != $newValue) {
                    $rawDiff[$key] = ['old' => $oldValue, 'new' => $newValue];
                }
            }

            // Snapshot the raw, per-column diff before it gets grouped into
            // the human-readable $diff below (e.g. three name fields become
            // one "name" entry) - Reject needs the real column names and
            // values to restore, not the display text.
            $revertDiff = $rawDiff;

            $diff = [];
            $nameFields = ['last_name', 'first_name', 'middle_name'];
            $hasNameChange = false;
            foreach ($nameFields as $field) {
                if (isset($rawDiff[$field])) {
                    $hasNameChange = true;
                    break;
                }
            }

            if ($hasNameChange) {
                $diff['name'] = [
                    'old' => $oldAttributes['full_name'] ?? null,
                    'new' => $fullName,
                ];
                foreach ($nameFields as $field) {
                    unset($rawDiff[$field]);
                }
            }

            if (isset($rawDiff['program_id'])) {
                $oldProgram = Program::find($oldAttributes['program_id'] ?? null);
                $diff['programme'] = [
                    'old' => $oldProgram?->code ?? $rawDiff['program_id']['old'],
                    'new' => $program->code ?? $rawDiff['program_id']['new'],
                ];
                unset($rawDiff['program_id']);
            }

            foreach ($rawDiff as $key => $change) {
                $diff[$key] = $change;
            }

            $graduationData['import_diff'] = $diff;
            $graduationData['import_diff_raw'] = $revertDiff;
            // A fresh update supersedes whatever review decision was made
            // on the previous one - it must be looked at again.
            $graduationData['import_review_status'] = 'pending';
            $graduationData['import_reviewed_by'] = null;
            $graduationData['import_reviewed_at'] = null;
            $graduation->fill($graduationData);
            $graduation->save();
            $report['updated']++;
            $report['updated_reg_numbers'][] = $registrationNumber;
        } else {
            $graduation = StudentGraduation::create(array_merge($graduationData, [
                'student_id' => $student->id,
                'is_graduated' => true,
            ]));
            $report['created']++;
            $report['created_reg_numbers'][] = $registrationNumber;
        }

        // Keep the main students row as a "latest graduation" cache for
        // views that still read flat fields (statistics, letters, search).
        $this->refreshStudentCache($student);

        if (! $startAcademicYear) {
            $report['flagged'][] = [
                'row' => $rowNumber,
                'registration_number' => $registrationNumber,
                'reason' => 'Could not derive the start Academic Year from the Registration Number - fill it in manually later on the student record.',
            ];
        }

        if ($sexRaw !== '' && $gender === null) {
            $report['flagged'][] = [
                'row' => $rowNumber,
                'registration_number' => $registrationNumber,
                'reason' => "Sex value '{$sexRaw}' was not recognised (expected M/F, Male/Female or Me/Ke) - left unset.",
            ];
        }
    }

    /**
     * Recomputes the `students` row from whichever of this student's
     * graduations is truly the latest (by year, then by id) - never assumed,
     * always re-queried, so this is safe to call after ANY write to any of
     * their graduations, not just the one that was just touched.
     *
     * `certificate_barcode` is the one field never blanked out by this sync:
     * a graduation with no certificate number yet (e.g. a brand new one just
     * created) must not erase an already-known barcode sitting on the
     * cache - certificate numbers are filled in later, per graduation, and
     * a still-empty one is "not yet known", not "cleared".
     */
    public function refreshStudentCache(Student $student): void
    {
        $latest = StudentGraduation::where('student_id', $student->id)
            ->orderByDesc('graduation_year')
            ->orderByDesc('id')
            ->first();

        if (! $latest) {
            return;
        }

        $first = $this->titleCaseName($latest->first_name ?? '');
        $middle = $this->titleCaseName($latest->middle_name ?? '');
        $fullName = trim(($latest->last_name ?? '').' '.$first.' '.$middle);

        $student->fill([
            'full_name' => $fullName,
            'last_name' => $latest->last_name,
            'first_name' => $latest->first_name,
            'middle_name' => $latest->middle_name,
            'gender' => $latest->gender,
            'campus_id' => $latest->campus_id,
            'program_id' => $latest->program_id,
            'degree_name' => $latest->degree_name,
            'degree_abbreviation' => $latest->degree_abbreviation,
            'graduation_year' => $latest->graduation_year,
            'graduation_date' => $latest->graduation_date,
            'academic_year' => null,
            'programme_start_academic_year' => $latest->programme_start_academic_year,
            'programme_end_academic_year' => $latest->programme_end_academic_year,
            'programme_duration_years' => $latest->programme_duration_years,
            'classification' => $latest->classification,
            'gpa' => $latest->gpa,
            'graduation_ceremony_number' => $latest->graduation_ceremony_number,
            'certificate_barcode' => $latest->certificate_barcode ?: $student->certificate_barcode,
            'raw_data' => $latest->raw_data,
            'imported_by' => $latest->imported_by,
            'roster_import_id' => $latest->roster_import_id,
            'import_diff' => $latest->import_diff,
            'is_graduated' => true,
        ]);
        $student->save();
    }

    /**
     * After a person edits a graduate's Programme and/or Graduation Year by
     * hand, brings the values derived from them along - duration, study
     * period, ceremony date - but only where the submitted value still
     * equals what the OLD Programme/Year would have derived. Anything
     * typed in deliberately is left exactly as entered. Works on the
     * unsaved, already-filled model.
     */
    public function syncDerivedFields(Student $student, ?Program $oldProgram, ?int $oldGraduationYear): void
    {
        $newProgram = $student->program_id ? Program::find($student->program_id) : null;
        $newYear = $student->graduation_year ? (int) $student->graduation_year : null;

        $programmeChanged = $newProgram?->id !== $oldProgram?->id;
        $yearChanged = $newYear !== $oldGraduationYear;

        if (! $programmeChanged && ! $yearChanged) {
            return;
        }

        $oldDuration = $oldProgram?->duration_years ? (int) $oldProgram->duration_years : null;
        $newDuration = $newProgram?->duration_years ? (int) $newProgram->duration_years : null;

        if ($programmeChanged && $newDuration) {
            $current = $student->programme_duration_years ? (int) $student->programme_duration_years : null;
            if ($current === null || $current === $oldDuration) {
                $student->programme_duration_years = $newDuration;
            }
        }

        $hasYearInRegNumber = (bool) preg_match('/^\d{4}\//', $student->registration_number);
        if (! $hasYearInRegNumber && $newYear && $oldGraduationYear) {
            $wasAutoDerived = $student->programme_start_academic_year === $this->deriveStartAcademicYear($student->registration_number, $oldGraduationYear, $oldDuration);
            if ($wasAutoDerived) {
                $student->programme_start_academic_year = $this->deriveStartAcademicYear($student->registration_number, $newYear, $newDuration ?? $oldDuration);
            }
        }

        if ($yearChanged && $newYear && $oldGraduationYear) {
            if ($student->programme_end_academic_year === ($oldGraduationYear - 1).'/'.$oldGraduationYear) {
                $student->programme_end_academic_year = ($newYear - 1).'/'.$newYear;
            }

            $oldCeremony = GraduationCeremony::where('year', $oldGraduationYear)->first();
            $currentDate = $student->graduation_date?->format('Y-m-d');
            if ($currentDate === null || $currentDate === $oldCeremony?->ceremony_date?->format('Y-m-d')) {
                $newCeremony = GraduationCeremony::where('year', $newYear)->first();
                $student->graduation_date = $newCeremony?->ceremony_date;
                $student->graduation_ceremony_number = $newCeremony?->sequence_number;
            }
        }
    }

    /**
     * Moves every student written by this batch to a different Programme
     * without re-uploading. Derived values follow the new Programme, but
     * only where they still hold the auto-derived value for the old one -
     * anything a person has since corrected by hand is left alone.
     */
    public function reassignProgramme(StudentRosterImport $batch, Program $newProgram): int
    {
        $oldDuration = $batch->program?->duration_years ? (int) $batch->program->duration_years : null;
        $newDuration = $newProgram->duration_years ? (int) $newProgram->duration_years : null;

        return DB::transaction(function () use ($batch, $newProgram, $oldDuration, $newDuration) {
            $moved = 0;

            Student::where('roster_import_id', $batch->id)->each(function (Student $student) use ($batch, $newProgram, $oldDuration, $newDuration, &$moved) {
                $changes = ['program_id' => $newProgram->id];

                $currentDuration = $student->programme_duration_years ? (int) $student->programme_duration_years : null;
                if ($newDuration && ($currentDuration === null || $currentDuration === $oldDuration)) {
                    $changes['programme_duration_years'] = $newDuration;
                }

                $hasYearInRegNumber = (bool) preg_match('/^\d{4}\//', $student->registration_number);
                if (! $hasYearInRegNumber && $student->graduation_year && $newDuration
                    && $student->programme_start_academic_year === $this->deriveStartAcademicYear($student->registration_number, $student->graduation_year, $oldDuration)) {
                    $changes['programme_start_academic_year'] = $this->deriveStartAcademicYear($student->registration_number, $student->graduation_year, $newDuration);
                }

                $student->update($changes);

                // Keep the matching StudentGraduation record in sync, not just the cached Student row.
                $graduation = $student->graduations()->where('roster_import_id', $batch->id)->first();
                if ($graduation) {
                    $gChanges = ['program_id' => $newProgram->id];

                    $gDuration = $graduation->programme_duration_years ? (int) $graduation->programme_duration_years : null;
                    if ($newDuration && ($gDuration === null || $gDuration === $oldDuration)) {
                        $gChanges['programme_duration_years'] = $newDuration;
                    }

                    $gStart = $graduation->programme_start_academic_year ? (int) $graduation->programme_start_academic_year : null;
                    if (! $hasYearInRegNumber && $graduation->graduation_year && $newDuration && $gStart !== null
                        && $gStart === $this->deriveStartAcademicYear($student->registration_number, $graduation->graduation_year, $oldDuration)) {
                        $gChanges['programme_start_academic_year'] = $this->deriveStartAcademicYear($student->registration_number, $graduation->graduation_year, $newDuration);
                    }

                    if (isset($gChanges['programme_start_academic_year']) && isset($gChanges['programme_duration_years'])) {
                        $gChanges['programme_end_academic_year'] = (int) $gChanges['programme_start_academic_year'] + $newDuration - 1;
                    } elseif (isset($gChanges['programme_duration_years']) && $gStart !== null) {
                        $gChanges['programme_end_academic_year'] = $gStart + $newDuration - 1;
                    }

                    $graduation->update($gChanges);
                }

                $moved++;
            });

            $batch->update([
                'original_program_id' => $batch->original_program_id ?? $batch->program_id,
                'program_id' => $newProgram->id,
            ]);

            return $moved;
        });
    }

    /**
     * Moves every student written by this batch to a different Graduation
     * Year without re-uploading. Derived values (academic years, ceremony
     * date and ceremony number) are recalculated for the new year, but only
     * where the student still holds the auto-derived value for the old one.
     */
    public function reassignYear(StudentRosterImport $batch, int $newYear): int
    {
        return DB::transaction(function () use ($batch, $newYear) {
            $moved = 0;
            $oldGraduationYear = $batch->graduation_year;

            Student::where('roster_import_id', $batch->id)->each(function (Student $student) use ($batch, $newYear, $oldGraduationYear, &$moved) {
                $oldProgram = $student->program;

                $student->update(['graduation_year' => $newYear]);
                $this->syncDerivedFields($student, $oldProgram, $oldGraduationYear);
                $student->save();

                $graduation = $student->graduations()->where('roster_import_id', $batch->id)->first();
                if ($graduation) {
                    $gChanges = ['graduation_year' => $newYear];

                    $newCeremony = GraduationCeremony::where('year', $newYear)->first();
                    $oldCeremony = GraduationCeremony::where('year', $oldGraduationYear)->first();
                    $currentDate = $graduation->graduation_date?->format('Y-m-d');
                    if ($currentDate === null || $currentDate === $oldCeremony?->ceremony_date?->format('Y-m-d')) {
                        $gChanges['graduation_date'] = $newCeremony?->ceremony_date;
                        $gChanges['graduation_ceremony_number'] = $newCeremony?->sequence_number;
                    }

                    $oldEndYear = $oldGraduationYear ? ($oldGraduationYear - 1).'/'.$oldGraduationYear : null;
                    $newEndYear = ($newYear - 1).'/'.$newYear;
                    if ($graduation->programme_end_academic_year === $oldEndYear) {
                        $gChanges['programme_end_academic_year'] = $newEndYear;
                    }

                    $graduation->update($gChanges);
                }

                $moved++;
            });

            $batch->update(['graduation_year' => $newYear]);

            return $moved;
        });
    }

    private function titleCaseName(string $name): string
    {
        if ($name === '') {
            return '';
        }

        return mb_convert_case(trim($name), MB_CASE_TITLE, 'UTF-8');
    }

    /**
     * Derive the start academic year from the registration number if possible,
     * when there is none, estimates it by counting back from the graduation
     * year by the programme's normal duration.
     */
    private function deriveStartAcademicYear(string $registrationNumber, int $graduationYear, ?int $durationYears): ?string
    {
        if (preg_match('/^(\d{4})\//', $registrationNumber, $matches)) {
            $year = (int) $matches[1];

            return $year.'/'.($year + 1);
        }

        if ($durationYears) {
            $year = $graduationYear - $durationYears;

            return $year.'/'.($year + 1);
        }

        return null;
    }

    private function normalizeSex(string $value): ?string
    {
        return match (mb_strtoupper(trim($value))) {
            'M', 'MALE', 'ME', 'MUME' => 'M',
            'F', 'FEMALE', 'KE', 'KIKE' => 'F',
            default => null,
        };
    }

    private function hasExpectedHeaders(mixed $headerRow): bool
    {
        if (! $headerRow) {
            return false;
        }

        foreach (self::EXPECTED_HEADERS as $i => $expected) {
            if (mb_strtolower(trim((string) ($headerRow[$i] ?? ''))) !== $expected) {
                return false;
            }
        }

        return true;
    }
